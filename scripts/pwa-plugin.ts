function manifest(): string {
  return JSON.stringify(
    {
      name: APP_NAME,
      short_name: APP_NAME,
      description: 'A personal historical timeline: the events you have encountered.',
      start_url: '.',
      scope: '.',
      display: 'standalone',
      orientation: 'any',
      background_color: THEME,
      theme_color: THEME,
      icons: [
        { src: 'icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' },
        { src: 'icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'maskable' },
      ],
    },
    null,
    2,
  );
}

function serviceWorker(version: string, assets: readonly string[]): string {
  return `/* Generated by scripts/pwa-plugin.ts — do not edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = 'arlinje-' + VERSION;
/**
 * Cache lookups ignore Vary.
 *
 * Servers commonly send "Vary: Origin" on static files, and Vite preview is one
 * of them. Precaching happens from the worker, which sends no Origin header; the
 * page then asks for the same file with crossorigin, which does. Under default
 * matching those count as different entries, so **every lookup missed** — the app
 * precached itself perfectly and then failed to load offline.
 *
 * Ignoring it is correct here rather than a workaround: Vary: Origin is a
 * statement about CORS, and these files are fingerprinted. One URL is one
 * immutable body, whoever asks.
 */
const MATCH = { ignoreVary: true };
const SHELL = ${JSON.stringify(assets)};

/**
 * Precaches the whole app, entry by entry.
 *
 * Deliberately not \`cache.addAll\`, which is atomic: one entry failing throws the
 * lot away, the install fails, and the app has no offline support at all until
 * something changes. For an offline-first app that trade is backwards — four
 * files out of five is worth having. It also sidesteps \`addAll\` rejecting with
 * "Entry already exists" when the server redirects one of the URLs, which is how
 * this was found.
 *
 * Stored against the requested URL rather than the response's, so a redirect
 * does not hide an entry under a name nothing will ask for.
 */
async function precache() {
  const cache = await caches.open(CACHE);
  await Promise.all(
    SHELL.map(async (path) => {
      const request = new Request(path, { cache: 'reload' });
      try {
        const response = await fetch(request);
        if (!response.ok) return;
        // Cloudflare's static assets answer index.html with a redirect to the
        // directory, and a redirected response is refused as the answer to a
        // navigation — so the offline fallback would fail. Store the body
        // under a clean response instead.
        const clean = response.redirected
          ? new Response(await response.blob(), {
              status: response.status,
              statusText: response.statusText,
              headers: response.headers,
            })
          : response;
        await cache.put(request, clean);
      } catch {
        // Offline during install, or one asset missing. The fetch handler falls
        // back to the network for anything not precached.
      }
    }),
  );
}

self.addEventListener('install', (event) => {
  event.waitUntil(precache());
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Network-first for the shell. Its URL is stable, so it is the only thing that
  // can go stale, and a local-first app running last week's code against this
  // week's database is the failure worth spending a round-trip to avoid.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          void caches.open(CACHE).then((cache) => cache.put(request, copy));
          return response;
        })
        .catch(() =>
          caches
            .match(request, MATCH)
            .then((hit) => hit ?? caches.match('index.html', MATCH)),
        ),
    );
    return;
  }

  // Everything else is fingerprinted by the build, so cache-first is exact.
  event.respondWith(
    caches.match(request, MATCH).then(
      (hit) =>
        hit ??
        fetch(request).then((response) => {
          if (response.ok && response.type === 'basic') {
            const copy = response.clone();
            void caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;
}

export function pwa(): Plugin {
  return {
    name: 'arlinje-pwa',
    apply: 'build',

    transformIndexHtml() {
      return [
        { tag: 'link', attrs: { rel: 'manifest', href: 'manifest.webmanifest' }, injectTo: 'head' },
        { tag: 'link', attrs: { rel: 'icon', type: 'image/svg+xml', href: 'icon.svg' }, injectTo: 'head' },
        { tag: 'meta', attrs: { name: 'theme-color', content: THEME }, injectTo: 'head' },
        {
          tag: 'meta',
          attrs: { name: 'apple-mobile-web-app-status-bar-style', content: 'black-translucent' },
          injectTo: 'head',
        },
      ];
    },

    generateBundle(_options, bundle) {
      // The precache list comes from the bundle itself, so it can never drift
      // from what was actually built — which is the one thing a hand-written
      // service worker usually gets wrong.
      const assets = ['index.html', 'manifest.webmanifest', 'icon.svg'];
      for (const file of Object.values(bundle)) {
        if (file.fileName === 'index.html') continue;
        assets.push(file.fileName);
      }

      // Hashed filenames are the version: if nothing changed, neither does this,
      // and the service worker does not needlessly evict a good cache.
      const version = hash(assets.join('\n'));

      this.emitFile({ type: 'asset', fileName: 'manifest.webmanifest', source: manifest() });
      this.emitFile({ type: 'asset', fileName: 'icon.svg', source: ICON });
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(version, assets) });
    },
  };
}

/** FNV-1a, which is plenty for a cache-busting token. */
function hash(text: string): string {
  let value = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    value ^= text.charCodeAt(i);
    value = Math.imul(value, 0x01000193) >>> 0;
  }
  return value.toString(36);
}
