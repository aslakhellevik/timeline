import type { Plugin } from 'vite';

/**
 * Emits the web app manifest and a service worker (docs/design.md §7, D36).
 *
 * Written here rather than pulled in as a plugin dependency, for the same reason
 * the Markdown renderer was (D27): what this needs is forty lines, and the
 * behaviour has to be *exactly* right in one respect — a local-first app that
 * serves a stale shell after an update is an app whose data model has moved on
 * without its code. Workbox would do this well, but it would also be a large
 * dependency whose caching strategy nobody here had read.
 *
 * The strategy, in full:
 *
 *   - **Hashed assets are cached forever.** Vite fingerprints them, so a given
 *     URL never changes contents and cache-first is safe.
 *   - **The HTML shell is network-first**, falling back to the cache offline.
 *     That is what stops a stale build persisting: the shell is the only file
 *     whose URL is stable, so it is the only one that can go stale.
 *   - **Nothing else is intercepted.** There is nothing else — the app makes no
 *     network requests at all once loaded (D25).
 */

